"""
r22_forum_eligibility.py
========================
**The single highest-priority script in this project at present.**

It answers a question that the existing manuscript does not ask, but that any referee
with a background in investment-arbitration law will certainly raise:

    How much of the measured "shift towards UNCITRAL / away from ICSID"
    is a mechanical consequence of the **States concerned having no ICSID Convention
    jurisdiction at all**, and how much reflects **UNCITRAL being chosen even where
    ICSID was legally available**?

Three outputs
-------------
A. `tab_elig_audit`      -- Convention-status eligibility audit (mechanical eligibility
                            gap between the treated and control groups)
B. `tab_elig_subsample`  -- re-estimates the headline within the subsample in which the
                            Convention is legally available, and estimates the new
                            outcome variable `natcourt_exposed`
C. `tab_elig_decomp`     -- Kitagawa–Oaxaca decomposition:
                            observed shift = choice-set composition
                                           + conditional forum selection

Three possible outcomes, each of which supports a good paper (see the decision tree in docs):
  (i)  conditional-selection term dominates -> the main result is **substantially
       strengthened**; the paper can be framed around routing/selection;
  (ii) composition term dominates          -> the finding is reframed as "sanctions
       co-move with exit from the ICSID Convention architecture", a stronger legal
       finding that maps exactly onto the "denationalisation" theme of
       Track 2 (denationalised finance);
  (iii) both terms comparable              -> report both layers side by side; still an
       upgrade on the current version.

Run (by default fully reuses the project's config / io_load; treatment variable S is
generated by build_cohorts)
----
    python src/r22_forum_eligibility.py --out paper_tables
    python src/r22_forum_eligibility.py --treat-var sanction_fin_count_it --threshold 3

Column names match the project's io_load: respondent_iso3, claimant_iso3, year, rules,
institution, is_uncitral, non_icsid, S, g, et (see _data.COL)
"""

